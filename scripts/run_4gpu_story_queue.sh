# Main
# ===========================================================================
# Standard "am I being sourced" idiom, so the helpers above can be sourced
# and exercised by a test without launching the queue. Used by
# scripts/test_story_queue.sh to verify the init_model_path trap handling.
(return 0 2>/dev/null) && return 0

if [ -n "${CUDA_VISIBLE_DEVICES:-}" ]; then
    IFS=',' read -r -a _cvd <<< "$CUDA_VISIBLE_DEVICES"
    LANE_A_GPU="${_cvd[0]:-$LANE_A_GPU}"
    LANE_B_GPU="${_cvd[1]:-$LANE_B_GPU}"
    LANE_C_GPU="${_cvd[2]:-$LANE_C_GPU}"
    LANE_D_GPU="${_cvd[3]:-$LANE_D_GPU}"
    log "CUDA_VISIBLE_DEVICES=$CUDA_VISIBLE_DEVICES -> lanes A/B/C/D on $LANE_A_GPU/$LANE_B_GPU/$LANE_C_GPU/$LANE_D_GPU"
    unset CUDA_VISIBLE_DEVICES
fi

rm -f "$STOP_FILE"
preflight || exit 1

if [ "$DRY_RUN" = "1" ]; then
    mkdir -p "$DRY_DIR"
    log "DRY RUN -- $PROBE_STEPS steps per stage (${PROBE_TIMEOUT}s backstop),"
    log "nothing real is trained."
    log "Stages run one at a time so the VRAM readings are not contaminated."
    echo
    [ -n "$PROBE_BATCHES" ] && \
        log "Sweeping train_batchsize over: $PROBE_BATCHES"
    # probe_one <key> <cfg> -- one row per swept batch, or one row at the
    # config's own batch when PROBE_BATCHES is empty.
    probe_one () {
        local pkey="$1" pcfg="$2" b
        if [ -z "$PROBE_BATCHES" ]; then
            probe_stage "$pkey" "$LANE_A_GPU" "$pcfg"
            return $?
        fi
        local oldifs="$IFS"; IFS=','
        for b in $PROBE_BATCHES; do
            IFS="$oldifs"
            probe_stage "$pkey" "$LANE_A_GPU" "$pcfg" "$b"
            IFS=','
        done
        IFS="$oldifs"
        return 0
    }

    for arm in $STORY_ARMS; do
        d="$(arm_dir "$arm")"
        echo "ARM $arm"
        [ "$arm" != "A0" ] && {
            probe_one "${arm}_pretrain" "$d/train.yaml"
            probe_one "${arm}_adapt"    "$d/train_10spks.yaml"
        }
        probe_one "${arm}_ft_msdwild" "$d/finetune_msdwild_10spks.yaml"
        [ -f "$d/finetune_msdwild_10spks_sub5.yaml" ] && \
            probe_one "${arm}_ft_msdwild_sub5" \
                "$d/finetune_msdwild_10spks_sub5.yaml"
        [ -f "$d/finetune_ramc_10spks.yaml" ] && \
            probe_one "${arm}_ft_ramc" "$d/finetune_ramc_10spks.yaml"
        [ -f "$d/finetune_ramc_10spks_sub5.yaml" ] && \
            probe_one "${arm}_ft_ramc_sub5" \
                "$d/finetune_ramc_10spks_sub5.yaml"
        echo
    done
    log "DRY RUN COMPLETE."
    log "Pick, per stage, the largest swept batch whose vram leaves ~2-3 GB of"
    log "headroom -- the probe never reaches the epoch-end dev pass, which"
    log "adds memory on top of what is reported here."
    log "Then set it in scripts/gen_story_queue_configs.py and regenerate;"
    log "do NOT edit the yaml by hand. For the pretrain and adapt stages the"
    log "Noam values must move WITH the batch (see that file's docstring) or"
    log "the LR schedule silently changes."
    log "Throwaway outputs are under $DRY_DIR (safe to delete)."
    exit 0
fi

log "STARTING story queue -- arms: $STORY_ARMS"
log "  lane A gpu $LANE_A_GPU: A4 pretrain->adapt->MSDWild->MSDWild@sub5"
log "  lane B gpu $LANE_B_GPU: A2 pretrain->adapt->MSDWild, then A4 RAMC@sub5"
log "  lane C gpu $LANE_C_GPU: A3 pretrain->adapt->MSDWild, then A4 RAMC@sub10"
log "  lane D gpu $LANE_D_GPU: A1 pretrain->adapt->MSDWild"

pids=()
for lane in A B C D; do
    if lane_enabled "$lane"; then
        ( "lane_$lane" ) > "$LOG_DIR/lane_$lane.log" 2>&1 &
        pids+=($!)
        log "  launched lane $lane (pid ${pids[-1]}) -> $LOG_DIR/lane_$lane.log"
    else
        log "  lane $lane disabled by ONLY_LANE=$ONLY_LANE"
    fi
done

rc=0
for p in "${pids[@]+"${pids[@]}"}"; do
    wait "$p" || rc=1
done

log "QUEUE FINISHED (rc=$rc)"
log "Scores: grep -h OVERALL $EXP_ROOT/SC_LibriSpeech_2spk_2500h_story_*/models_finetune*/*/dscore_*.log"
exit $rc
